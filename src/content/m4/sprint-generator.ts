/**
 * Deterministically generates today's 5-item Mind Sprint based on date seed string.
 */
export function getDailySprint(dateString: string): DailySprint {
  // Simple deterministic hash from date string
  let hash = 0;
  for (let i = 0; i < dateString.length; i++) {
    hash = (hash << 5) - hash + dateString.charCodeAt(i);
    hash |= 0;
  }
  const seed = Math.abs(hash);

  const pattern = PATTERN_POOL[seed % PATTERN_POOL.length];
  const deduction = DEDUCTION_POOL[(seed >> 2) % DEDUCTION_POOL.length];
  const memory = MEMORY_POOL[(seed >> 4) % MEMORY_POOL.length];
  const numerical = NUMERICAL_POOL[(seed >> 6) % NUMERICAL_POOL.length];
  const tricky = TRICKY_POOL[(seed >> 8) % TRICKY_POOL.length];

  const items: SprintItem[] = [
    { ...pattern, id: `${dateString}-p1` },
    { ...deduction, id: `${dateString}-d2` },
    { ...memory, id: `${dateString}-m3` },
    { ...numerical, id: `${dateString}-n4` },
    { ...tricky, id: `${dateString}-t5` },
  ];

  return {
    date: dateString,
    seed: `sprint-${seed}`,
    totalTimeSec: 300, // 45 + 60 + 45 + 60 + 90 = 300s (5 minutes)
    items,
  };
}
